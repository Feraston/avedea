import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const PUBLIC = path.join(ROOT, "public");

const pageEntries = [
  "index.css",
  "services.css",
  "services/uslugi.css",
  "abon/abon.css",
  "spec/pers.css",
  "training.css",
].map((f) => path.join(PUBLIC, "pages", f));

/** Old hover-card sale pieces replaced by .offer-card in overrides.css */
const SKIP = new Set(
  [
    "blocks/sale/__card/sale__card.css",
    "blocks/sale/__card-img/sale__card-img.css",
    "blocks/sale/__img/sale__img.css",
    "blocks/sale/__card-content/sale__card-content.css",
    "blocks/sale/__details/sale__details.css",
    "blocks/sale/__card-title/sale__card-title.css",
    "blocks/sale/__card-link/sale__card-link.css",
    "blocks/sale/__card-subtitle/sale__card-subtitle.css",
    "blocks/sale/__main/sale__main.css",
    "blocks/sale/__weight/sale__weight.css",
    "blocks/sale/__text/sale__text.css",
    "blocks/sale/__btn/sale__btn.css",
    "blocks/sale/__botton/sale__botton.css",
    "blocks/sale/__details/_normal/sale__details_normal-one.css",
    "blocks/sale/__details/_normal/sale__details_normal-two.css",
    "blocks/sale/__details/_normal/sale__details_normal-three.css",
    "pages/catalog.css",
  ].map((p) => path.join(PUBLIC, p).replace(/\\/g, "/"))
);

function toPosix(p) {
  return p.replace(/\\/g, "/");
}

function collectImports(entryFile, seen = new Set(), ordered = []) {
  const text = fs.readFileSync(entryFile, "utf8");
  const dir = path.dirname(entryFile);
  for (const match of text.matchAll(/@import\s+url\(([^)]+)\)\s*;?/g)) {
    const raw = match[1].trim().replace(/^['"]|['"]$/g, "");
    const abs = path.normalize(path.join(dir, raw));
    const key = toPosix(abs);
    if (SKIP.has(key) || seen.has(key)) continue;
    if (!fs.existsSync(abs)) {
      console.warn("Missing CSS:", abs);
      continue;
    }
    seen.add(key);
    // Recurse first if this file also imports (fonts/normalize don't)
    const nested = fs.readFileSync(abs, "utf8");
    if (/@import\s+url\(/.test(nested)) {
      collectImports(abs, seen, ordered);
    } else {
      ordered.push(abs);
    }
  }
  return ordered;
}

function rewriteUrls(cssText, cssFileAbs) {
  const cssDir = path.dirname(cssFileAbs);
  return cssText.replace(/url\(([^)]+)\)/g, (full, raw) => {
    let u = raw.trim().replace(/^['"]|['"]$/g, "");
    if (
      !u ||
      u.startsWith("data:") ||
      u.startsWith("http:") ||
      u.startsWith("https:") ||
      u.startsWith("//") ||
      u.startsWith("/")
    ) {
      return full;
    }
    const absAsset = path.normalize(path.join(cssDir, u));
    const relFromPublic = toPosix(path.relative(PUBLIC, absAsset));
    if (relFromPublic.startsWith("..")) return full;
    return `url(/${relFromPublic})`;
  });
}

const seen = new Set();
const ordered = [];
for (const entry of pageEntries) {
  collectImports(entry, seen, ordered);
}

// Also append overrides (not via @import chain from pages)
const overrides = path.join(PUBLIC, "styles", "overrides.css");

const parts = [
  "/* Auto-generated by scripts/build-site-css.mjs — do not edit */",
  `/* ${ordered.length} stylesheets inlined */`,
];

for (const file of ordered) {
  let body = fs.readFileSync(file, "utf8");
  // Strip nested @imports (already flattened)
  body = body.replace(/@import\s+url\([^)]+\)\s*;?/g, "");
  body = rewriteUrls(body, file);
  parts.push(`\n/* --- ${toPosix(path.relative(PUBLIC, file))} --- */\n`);
  parts.push(body.trim());
}

if (fs.existsSync(overrides)) {
  let body = fs.readFileSync(overrides, "utf8");
  body = rewriteUrls(body, overrides);
  parts.push("\n/* --- styles/overrides.css --- */\n");
  parts.push(body.trim());
}

const outPath = path.join(PUBLIC, "styles", "site.css");
fs.writeFileSync(outPath, parts.join("\n") + "\n", "utf8");
console.log(
  `Wrote ${path.relative(ROOT, outPath)} (${ordered.length} files, ${(fs.statSync(outPath).size / 1024).toFixed(1)} KB)`
);
